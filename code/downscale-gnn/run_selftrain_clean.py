"""
Clean self-training: Phase 1 trained WITHOUT auxiliary stations,
auxiliary stations + pseudo-labels added in Phase 4 only.

  Phase 1   : train on N_UNLABELED=0 graph (58 nodes: 50 train + 8 valid)
              → strongest "no unlabeled used" baseline
  Phase 1.5 : snapshot collection, still on small graph
  Phase 2   : reload data with N_UNLABELED=ST_PHASE4_N_UNLABELED (default 400),
              apply each snapshot to the larger graph for ε̂ predictions
              → pseudo-labels generated by transferring small-graph models to large graph
  Phase 3   : confidence×diversity×relevance selection from candidates
  Phase 4   : fresh model on full graph, sup loss + pseudo loss

Compared to run_selftrain_ead.py (which uses aux throughout):
  ✓ Phase 1 = clean baseline (no unlabeled = "supervised baseline" the user asked for)
  ✓ Phase 4 - Phase 1 = pure self-training contribution (no architectural confound)
"""
import os
import copy
import pickle
from datetime import datetime

import numpy as np
import torch
import wandb

import data_semi, network_semi, utils

# Reuse helper functions from run_selftrain_ead.py
from run_selftrain_ead import (
    precompute_alpha_beta,
    attach_to_dataset,
    train_ead_epoch,
    eval_ead,
    predict_eps_all,
    per_station_embedding,
    greedy_select,
    aggregate_snapshots,
)


# =========================================================================
# Setup
# =========================================================================
device   = torch.device("cuda:0") if torch.cuda.is_available() else torch.device('cpu')
path     = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data')
project_root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
conv_type = os.environ.get('CONV_TYPE', 'graphconv').lower()
timestamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
job_id    = os.environ.get('SLURM_JOB_ID', '')

# EAD config (mirror run_selftrain_ead so imported helpers behave correctly)
EAD_ALPHA = int(os.environ.get('EAD_ALPHA', '1'))
EAD_BETA  = int(os.environ.get('EAD_BETA',  '0'))
EAD_LAP   = int(os.environ.get('EAD_LAP',   '1'))
LAMBDA_LAP = float(os.environ.get('LAMBDA_LAP', '0.1')) if EAD_LAP else 0.0
USE_GNN = int(os.environ.get('USE_GNN', '1'))
N_GNN   = int(os.environ.get('N_GNN', '3'))

# Self-training config
ST_PHASE1_EPOCHS = int(os.environ.get('ST_PHASE1_EPOCHS', '500'))
ST_PHASE4_EPOCHS = int(os.environ.get('ST_PHASE4_EPOCHS', '4000'))
ST_M_SNAPSHOTS   = int(os.environ.get('ST_M_SNAPSHOTS', '5'))
ST_T_CYCLE       = int(os.environ.get('ST_T_CYCLE', '40'))
ST_LR_MAX        = float(os.environ.get('ST_LR_MAX', '1e-3'))
ST_LR_MIN        = float(os.environ.get('ST_LR_MIN', '1e-5'))
ST_TAU_QUANTILE  = float(os.environ.get('ST_TAU_QUANTILE', '0.5'))
ST_K             = int(os.environ.get('ST_K', '100'))
ST_ALPHA_DIV     = float(os.environ.get('ST_ALPHA_DIV', '1.0'))
ST_BETA_REL      = float(os.environ.get('ST_BETA_REL', '1.0'))
ST_K_NN_REL      = int(os.environ.get('ST_K_NN_REL', '5'))
ST_LAMBDA_PSEUDO = float(os.environ.get('ST_LAMBDA_PSEUDO', '0.5'))
ST_ABLATION      = os.environ.get('ST_ABLATION', 'full').lower()

# Two N_UNLABELED values - this is the core of the clean variant
ST_PHASE1_N_UNLABELED = int(os.environ.get('ST_PHASE1_N_UNLABELED', '0'))
ST_PHASE4_N_UNLABELED = int(os.environ.get('ST_PHASE4_N_UNLABELED', '400'))

st_tag = f"st_clean_{ST_ABLATION}_K{ST_K}_M{ST_M_SNAPSHOTS}"
output_dir = os.path.join(project_root, 'log',
                          f'job{job_id}_{st_tag}_{timestamp}' if job_id else f'{st_tag}_{timestamp}')
os.makedirs(output_dir, exist_ok=True)
os.environ['OUTPUT_DIR'] = output_dir


# =========================================================================
# Data loading helper
# =========================================================================
def make_dataloader(n_unlabeled):
    """Returns (trainLoader, validLoader, metadata, validSet)."""
    dataParam = {
        'geoMethod': 'average', 'nCompPCA': 40, 'window': 2,
        'poolSize': int(os.environ.get('POOL_SIZE', '12')),
        'batchSize': 512, 'thres': 0.1,
        'geoFeatures': 'full', 'n_unlabeled': n_unlabeled,
    }
    os.environ.setdefault('EVAL_MODE', 'spatial')
    os.environ.setdefault('USE_FPS', '2')
    os.environ.setdefault('EDGE_MODE', 'no_uu')
    os.environ.setdefault('NORM_MODE', 'global')
    return data_semi.dataGen(dataParam, path)


# =========================================================================
# Main pipeline
# =========================================================================
def main():
    log_path = os.path.join(output_dir, f'selftrain_clean_{ST_ABLATION}_log')
    with open(log_path, 'w') as f:
        f.write(f"=== Clean self-training pipeline ===\n")
        f.write(f"Phase1_N_UNLABELED={ST_PHASE1_N_UNLABELED}, "
                f"Phase4_N_UNLABELED={ST_PHASE4_N_UNLABELED}\n")
        f.write(f"ablation={ST_ABLATION}, K={ST_K}, M={ST_M_SNAPSHOTS}, "
                f"τ={ST_TAU_QUANTILE}, λ_pseudo={ST_LAMBDA_PSEUDO}\n")

    modelParam_template = lambda iDim, oDim: {
        'HLD': 128, 'nMLP': 2, 'nGNN': N_GNN, 'nGAT': 1, 'nHeads': 1, 'K': 1,
        'iDim': iDim, 'oDim': oDim,
        'BN': False, 'Dropout': True, 'conv_type': conv_type,
        'use_gnn': bool(USE_GNN),
    }

    modelName = f"selftrain_clean_{ST_ABLATION}"

    # =====================================================================
    # Load SMALL graph (Phase 1 / 1.5)
    # =====================================================================
    print("\n" + "#"*72)
    print(f"# Loading SMALL dataset (N_UNLABELED={ST_PHASE1_N_UNLABELED}) for Phase 1 / 1.5")
    print("#"*72)
    trainL_small, validL_small, meta_small, _ = make_dataloader(ST_PHASE1_N_UNLABELED)
    nNodes_small = meta_small['nNodes']
    nNodes_labeled = meta_small['nNodes_labeled']
    train_idx_small = meta_small['train_station_idx']
    valid_idx_small = meta_small['valid_station_idx']
    tgt_scl_celsius = float(meta_small.get('tgt_global_scl', 1.0))

    alpha_per_sample, beta_hat_small, _ = precompute_alpha_beta(trainL_small, meta_small)
    attach_to_dataset(trainL_small.dataset, alpha_per_sample, beta_hat_small)
    attach_to_dataset(validL_small.dataset, alpha_per_sample, beta_hat_small)

    Adj_s = meta_small['AdjMatrix']
    src_s, dst_s = np.nonzero(Adj_s)
    edge_src_s = torch.LongTensor(src_s).to(device)
    edge_dst_s = torch.LongTensor(dst_s).to(device)
    edge_w_s   = torch.FloatTensor(Adj_s[src_s, dst_s]).to(device)

    modelParam_small = modelParam_template(meta_small['iDim'], meta_small['oDim'])

    # ---- wandb ----
    wandb.init(
        entity="urban_prediction", project="Semi-supervised GNN",
        name=f"{modelName}_job{job_id}" if job_id else modelName,
        config={**modelParam_small,
                'ST_ABLATION': ST_ABLATION,
                'ST_PHASE1_EPOCHS': ST_PHASE1_EPOCHS,
                'ST_PHASE4_EPOCHS': ST_PHASE4_EPOCHS,
                'ST_M_SNAPSHOTS': ST_M_SNAPSHOTS, 'ST_T_CYCLE': ST_T_CYCLE,
                'ST_K': ST_K, 'ST_LAMBDA_PSEUDO': ST_LAMBDA_PSEUDO,
                'ST_PHASE1_N_UNLABELED': ST_PHASE1_N_UNLABELED,
                'ST_PHASE4_N_UNLABELED': ST_PHASE4_N_UNLABELED,
                'EAD_ALPHA': EAD_ALPHA, 'LAMBDA_LAP': LAMBDA_LAP,
                'variant': 'clean'},
    )

    # =====================================================================
    # PHASE 1
    # =====================================================================
    print("\n" + "#"*72)
    print(f"# PHASE 1 — base training on {nNodes_small} nodes (no aux)")
    print("#"*72)
    gnn = network_semi.GNN(modelParam_small).to(device)
    opt = torch.optim.Adam(gnn.parameters(), lr=1e-3)
    scheduler = torch.optim.lr_scheduler.ExponentialLR(opt, gamma=0.9992)

    best_p1_rmse = float('inf')
    best_p1_state = None
    for epoch in range(ST_PHASE1_EPOCHS):
        stats, train_rmse = train_ead_epoch(
            trainL_small, gnn, opt, scheduler, device,
            nNodes_small, edge_src_s, edge_dst_s, edge_w_s, use_pseudo=False)
        em = eval_ead(validL_small, gnn, device, nNodes_small, nNodes_labeled, tgt_scl=tgt_scl_celsius)
        v_rmse = em['rmse_norm']
        if v_rmse < best_p1_rmse:
            best_p1_rmse = v_rmse
            best_p1_state = copy.deepcopy(gnn.state_dict())
        if epoch % 25 == 0 or epoch < 3:
            line = (f"P1 ep{epoch:4d}: train_RMSE={train_rmse[0]:.4f}  "
                    f"valid_RMSE={v_rmse:.4f} ({em['rmse_C']:.3f}°C)")
            print(line)
            with open(log_path, 'a') as f: f.write(line + '\n')
        wandb.log({'phase': 1, 'epoch_p1': epoch,
                   'p1/train_rmse': train_rmse[0], 'p1/valid_rmse': v_rmse,
                   'p1/best_valid_rmse': best_p1_rmse})

    print(f"\n  [Phase 1 — clean baseline, no aux] best valid_RMSE = {best_p1_rmse:.4f}")
    with open(log_path, 'a') as f:
        f.write(f"[Phase 1 done] best_valid_RMSE={best_p1_rmse:.4f}\n")
    gnn.load_state_dict(best_p1_state)

    # =====================================================================
    # PHASE 1.5
    # =====================================================================
    print("\n" + "#"*72)
    print(f"# PHASE 1.5 — Snapshot Ensemble (M={ST_M_SNAPSHOTS}, T={ST_T_CYCLE}) on small graph")
    print("#"*72)
    for pg in opt.param_groups: pg['lr'] = ST_LR_MAX
    snap_sched = torch.optim.lr_scheduler.CosineAnnealingWarmRestarts(
        opt, T_0=ST_T_CYCLE, T_mult=1, eta_min=ST_LR_MIN)

    snapshot_states = []
    snapshot_valid_rmses = []
    total_snap_ep = ST_M_SNAPSHOTS * ST_T_CYCLE
    for ep in range(total_snap_ep):
        train_ead_epoch(trainL_small, gnn, opt, snap_sched, device,
                        nNodes_small, edge_src_s, edge_dst_s, edge_w_s, use_pseudo=False)
        if (ep + 1) % ST_T_CYCLE == 0:
            snapshot_states.append(copy.deepcopy(gnn.state_dict()))
            ev = eval_ead(validL_small, gnn, device, nNodes_small, nNodes_labeled, tgt_scl=tgt_scl_celsius)
            snapshot_valid_rmses.append(ev['rmse_norm'])
            line = (f"  [Snapshot {len(snapshot_states)}/{ST_M_SNAPSHOTS}] "
                    f"valid_RMSE={ev['rmse_norm']:.4f}")
            print(line)
            with open(log_path, 'a') as f: f.write(line + '\n')

    sn = np.array(snapshot_valid_rmses)
    print(f"\n  [Snapshot diag] valid_RMSE per snapshot: {snapshot_valid_rmses}")
    print(f"  [Snapshot diag] mean={sn.mean():.4f}, std={sn.std():.4f} (want std > 0)")

    # Free small-graph dataloaders
    del trainL_small, validL_small

    # =====================================================================
    # Load FULL graph (Phase 2/3/4)
    # =====================================================================
    print("\n" + "#"*72)
    print(f"# Loading FULL dataset (N_UNLABELED={ST_PHASE4_N_UNLABELED}) for Phase 2/3/4")
    print("#"*72)
    trainL_full, validL_full, meta_full, _ = make_dataloader(ST_PHASE4_N_UNLABELED)
    nNodes_full = meta_full['nNodes']
    train_idx_full = meta_full['train_station_idx']
    valid_idx_full = meta_full['valid_station_idx']

    # Sanity: the labeled stations should be the same in both datasets
    assert np.array_equal(np.sort(train_idx_small), np.sort(train_idx_full)), \
        "Train stations differ between small and full datasets — fix data loading!"
    assert np.array_equal(np.sort(valid_idx_small), np.sort(valid_idx_full)), \
        "Valid stations differ between small and full datasets — fix data loading!"

    alpha_full, beta_hat_full, _ = precompute_alpha_beta(trainL_full, meta_full)
    attach_to_dataset(trainL_full.dataset, alpha_full, beta_hat_full)
    attach_to_dataset(validL_full.dataset, alpha_full, beta_hat_full)

    # Sanity: alpha must be identical (computed from same labeled data)
    print(f"\n  [Sanity] α difference (small vs full datasets): "
          f"max abs = {np.abs(alpha_per_sample - alpha_full).max():.6f} (should be ~0)")

    Adj_f = meta_full['AdjMatrix']
    src_f, dst_f = np.nonzero(Adj_f)
    edge_src_f = torch.LongTensor(src_f).to(device)
    edge_dst_f = torch.LongTensor(dst_f).to(device)
    edge_w_f   = torch.FloatTensor(Adj_f[src_f, dst_f]).to(device)

    modelParam_full = modelParam_template(meta_full['iDim'], meta_full['oDim'])
    assert modelParam_full['iDim'] == modelParam_small['iDim'], \
        f"iDim differs: small={modelParam_small['iDim']} vs full={modelParam_full['iDim']}"

    # =====================================================================
    # PHASE 2 — apply snapshots to FULL graph
    # =====================================================================
    print("\n" + "#"*72)
    print(f"# PHASE 2 — applying snapshots to FULL graph ({nNodes_full} nodes)")
    print("#"*72)
    snap_preds = []
    for i, state in enumerate(snapshot_states):
        gnn_p2 = network_semi.GNN(modelParam_full).to(device)
        gnn_p2.load_state_dict(state)
        eps_pred = predict_eps_all(gnn_p2, trainL_full.dataset, device, nNodes_full)
        snap_preds.append(eps_pred)
        print(f"  [snapshot {i+1}] ε̂ on full graph: mean={eps_pred.mean():+.4f}, "
              f"std={eps_pred.std():.4f}, "
              f"per-node std (over t): mean={eps_pred.std(axis=0).mean():.4f}")

    ensemble_mean, ensemble_std, conf_per_station = aggregate_snapshots(snap_preds)

    print(f"\n  [Ensemble σ] mean={ensemble_std.mean():.4f}, "
          f"std={ensemble_std.std():.4f}, max={ensemble_std.max():.4f}")
    cand_idx = np.arange(nNodes_labeled, nNodes_full)
    print(f"  [Confidence] train mean = {conf_per_station[train_idx_full].mean():+.4f}")
    print(f"  [Confidence] valid mean = {conf_per_station[valid_idx_full].mean():+.4f}")
    print(f"  [Confidence] cand  mean = {conf_per_station[cand_idx].mean():+.4f}")

    # ---- Pseudo-label QUALITY check on V ----
    all_delta = np.zeros((len(trainL_full.dataset), nNodes_full), dtype=np.float32)
    for t, d in enumerate(trainL_full.dataset):
        all_delta[t] = d.y_residual.squeeze(-1).cpu().numpy()
    true_eps_all = all_delta - alpha_full[:, None] - beta_hat_full[None, :]
    pseudo_rmse_v = np.sqrt(
        ((ensemble_mean[:, valid_idx_full] - true_eps_all[:, valid_idx_full]) ** 2).mean(axis=0)
    )
    pseudo_rmse_train = np.sqrt(
        ((ensemble_mean[:, train_idx_full] - true_eps_all[:, train_idx_full]) ** 2).mean(axis=0)
    )
    print(f"\n  [Pseudo-label QUALITY check]")
    print(f"    ε̂ RMSE on TRAIN labeled : mean={pseudo_rmse_train.mean():.4f}")
    print(f"    ε̂ RMSE on VALID labeled : mean={pseudo_rmse_v.mean():.4f}  std={pseudo_rmse_v.std():.4f}")
    print(f"    Reference Phase 1 best  : {best_p1_rmse:.4f}")
    quality_warnings = []
    if pseudo_rmse_v.mean() > 1.5 * best_p1_rmse:
        msg = (f"⚠ Pseudo ε̂ RMSE on V = {pseudo_rmse_v.mean():.4f} "
               f"> 1.5× Phase1 best {best_p1_rmse:.4f}")
        print(f"    {msg}")
        quality_warnings.append(msg)
    else:
        print(f"    ✓ Ensemble quality on V is comparable to Phase 1.")

    # ---- Over-smoothing check ----
    true_spatial_std   = true_eps_all[:, cand_idx].std(axis=1).mean()
    pseudo_spatial_std = ensemble_mean[:, cand_idx].std(axis=1).mean()
    smooth_ratio = pseudo_spatial_std / (true_spatial_std + 1e-8)
    print(f"\n  [Over-smoothing check]")
    print(f"    true ε spatial std   = {true_spatial_std:.4f}")
    print(f"    pseudo ε spatial std = {pseudo_spatial_std:.4f}")
    print(f"    ratio pseudo/true    = {smooth_ratio:.3f}")
    if smooth_ratio < 0.7:
        msg = f"⚠ Over-smoothing: ratio = {smooth_ratio:.3f} < 0.7"
        print(f"    {msg}"); quality_warnings.append(msg)
    elif smooth_ratio > 1.3:
        msg = f"⚠ Spatial std ratio {smooth_ratio:.3f} > 1.3 (overfitting noise?)"
        print(f"    {msg}"); quality_warnings.append(msg)
    else:
        print(f"    ✓ ratio in [0.7, 1.3] — preserves spatial diversity.")

    # ---- Embeddings (last snapshot, full graph) ----
    gnn_p2 = network_semi.GNN(modelParam_full).to(device)
    gnn_p2.load_state_dict(snapshot_states[-1])
    emb_per_st = per_station_embedding(gnn_p2, trainL_full.dataset, device, nNodes_full)
    print(f"\n  [Embedding] shape={emb_per_st.shape}, "
          f"per-station norm: mean={np.linalg.norm(emb_per_st, axis=1).mean():.3f}")

    # =====================================================================
    # PHASE 3 — selection
    # =====================================================================
    print("\n" + "#"*72)
    print(f"# PHASE 3 — selection (ablation = {ST_ABLATION})")
    print("#"*72)
    selected_global = greedy_select(
        emb_all=emb_per_st,
        candidate_idx=cand_idx,
        valid_idx=valid_idx_full,
        confidence_per_station=conf_per_station,
        K=ST_K, alpha=ST_ALPHA_DIV, beta=ST_BETA_REL,
        k_nn_rel=ST_K_NN_REL, tau_quantile=ST_TAU_QUANTILE,
        ablation=ST_ABLATION,
    )

    select_mask = np.zeros(nNodes_full, dtype=bool)
    select_mask[selected_global] = True
    print(f"  [Selection] |S|={select_mask.sum()}")

    sel_idx = np.array(selected_global)
    unsel_idx = np.array([i for i in cand_idx if not select_mask[i]])
    if len(unsel_idx) > 0:
        sel_conf = conf_per_station[sel_idx]
        unsel_conf = conf_per_station[unsel_idx]
        print(f"\n  [Selection sanity]")
        print(f"    selected   conf mean: {sel_conf.mean():+.4f}")
        print(f"    unselected conf mean: {unsel_conf.mean():+.4f}")
        print(f"    Δ = {sel_conf.mean()-unsel_conf.mean():+.4f}  (want > 0)")

    with open(os.path.join(output_dir, 'selection.pkl'), 'wb') as f:
        pickle.dump({
            'selected_global': selected_global,
            'select_mask': select_mask,
            'confidence': conf_per_station,
            'embeddings': emb_per_st,
            'ablation': ST_ABLATION,
            'snapshot_valid_rmses': snapshot_valid_rmses,
            'phase1_best_rmse': best_p1_rmse,
            'pseudo_rmse_v': pseudo_rmse_v,
            'smooth_ratio': float(smooth_ratio),
        }, f)

    # =====================================================================
    # PHASE 4 — retrain on FULL graph with sup + pseudo loss
    # =====================================================================
    print("\n" + "#"*72)
    print(f"# PHASE 4 — retrain on FULL graph (λ_pseudo={ST_LAMBDA_PSEUDO}, K={int(select_mask.sum())})")
    print("#"*72)
    attach_to_dataset(trainL_full.dataset, alpha_full, beta_hat_full,
                      pseudo_eps_all=ensemble_mean,
                      pseudo_sigma_all=ensemble_std,
                      pseudo_select_mask=select_mask)
    attach_to_dataset(validL_full.dataset, alpha_full, beta_hat_full)

    gnn4 = network_semi.GNN(modelParam_full).to(device)
    opt4 = torch.optim.Adam(gnn4.parameters(), lr=1e-3)
    sched4 = torch.optim.lr_scheduler.ExponentialLR(opt4, gamma=0.9992)

    best_p4_rmse = float('inf')
    best_p4_metrics = None
    for epoch in range(ST_PHASE4_EPOCHS):
        stats, train_rmse = train_ead_epoch(
            trainL_full, gnn4, opt4, sched4, device,
            nNodes_full, edge_src_f, edge_dst_f, edge_w_f,
            use_pseudo=True, lambda_pseudo=ST_LAMBDA_PSEUDO)
        em = eval_ead(validL_full, gnn4, device, nNodes_full, nNodes_labeled, tgt_scl=tgt_scl_celsius)
        v_rmse = em['rmse_norm']
        if v_rmse < best_p4_rmse:
            best_p4_rmse = v_rmse
            best_p4_metrics = em
            torch.save({
                'epoch': epoch,
                'gnn_state_dict': gnn4.state_dict(),
                'bestLoss': best_p4_rmse,
                'selected_global': selected_global,
            }, os.path.join(output_dir, f'{modelName}.pt'))
        if epoch % 25 == 0 or epoch < 3:
            line = (f"P4 ep{epoch:4d}: train={train_rmse[0]:.4f} "
                    f"valid={v_rmse:.4f} ({em['rmse_C']:.3f}°C)  "
                    f"sup={stats['sup_eps']:.4e} pseudo={stats['pseudo']:.4e} "
                    f"lap={stats['lap']:.4e}")
            print(line)
            with open(log_path, 'a') as f: f.write(line + '\n')
        pseudo_to_sup = (ST_LAMBDA_PSEUDO * stats['pseudo']) / (stats['sup_eps'] + 1e-8)
        wandb.log({
            'phase': 4, 'epoch_p4': epoch,
            'p4/train_rmse': train_rmse[0], 'p4/valid_rmse': v_rmse,
            'p4/valid_rmseC': em['rmse_C'],
            'p4/sup_loss': stats['sup_eps'], 'p4/pseudo_loss': stats['pseudo'],
            'p4/lap_loss': stats['lap'],
            'p4/pseudo_to_sup_ratio': pseudo_to_sup,
            'p4/best_valid_rmse': best_p4_rmse,
            'metrics/rmse_norm': em['rmse_norm'],
            'metrics/rmse_C':    em['rmse_C'],
            'metrics/mbe_norm':  em['mbe_norm'],
            'metrics/mae_norm':  em['mae_norm'],
        })

    # =====================================================================
    # FINAL
    # =====================================================================
    print("\n" + "="*72)
    print("  FINAL RESULTS  (clean variant — Phase 1 had NO aux)")
    print("="*72)
    print(f"  Phase 1 best (clean baseline, no aux)         : {best_p1_rmse:.4f} "
          f"({best_p1_rmse * tgt_scl_celsius:.3f}°C)")
    print(f"  Phase 4 best (full graph + pseudo-labels)     : {best_p4_rmse:.4f} "
          f"({best_p4_metrics['rmse_C']:.3f}°C)")
    delta = best_p1_rmse - best_p4_rmse
